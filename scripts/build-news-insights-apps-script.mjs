import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const root = resolve(
  dirname(fileURLToPath(import.meta.url)),
  "../integrations/google-apps-script/news-insights",
);

async function bundle(entry, globalName, wrappers) {
  const result = await build({
    entryPoints: [entry],
    bundle: true,
    charset: "utf8",
    format: "iife",
    globalName,
    target: "es2019",
    platform: "browser",
    write: false,
    banner: { js: "// Generated by scripts/build-news-insights-apps-script.mjs. Do not edit." },
    footer: {
      js: wrappers,
    },
  });
  const output = result.outputFiles[0]?.text;
  if (!output || /__require\(|require\(/u.test(output))
    throw new Error("뉴스 artifact의 외부 의존성을 확인하세요.");
  return output;
}

/** 시트 관리와 서명된 후보 수집 작업만 제공한다. 공개 뉴스 읽기는 별도 artifact다. */
export function buildNewsInsightsBundle() {
  return bundle(
    resolve(root, "src/entrypoint.ts"),
    "NewsInsights",
    ["onOpenNews", "showNewsSidebar", "newsList", "newsMutate", "newsCollectionStatus"]
      .map((name) => `function ${name}(value) { return NewsInsights.${name}(value); }`)
      .join("\n") +
      "\nfunction onOpen(e) { return NewsInsights.onOpenNews(e); }\nfunction doPost(e) { return NewsInsights.doPostNewsWorker(e); }",
  );
}

/** 공개 artifact는 읽기 전용 원본만 남기고 관리·쓰기·수집 코드를 제거한다. */
export function buildNewsPublicBundle() {
  return bundle(
    resolve(root, "../news-public/src/entrypoint.ts"),
    "NewsPublic",
    "function doGet(e) { return NewsPublic.doGetNews(e); }",
  );
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  for (const [directory, buildBundle] of [
    [root, buildNewsInsightsBundle],
    [resolve(root, "../news-public"), buildNewsPublicBundle],
  ]) {
    const output = await buildBundle();
    const target = resolve(directory, "Code.gs");
    if (process.argv.includes("--check")) {
      if (!existsSync(target) || readFileSync(target, "utf8") !== output) {
        console.error("뉴스 Code.gs가 원본과 다릅니다. npm run build:apps-script를 실행하세요.");
        process.exitCode = 1;
      } else console.log("News Apps Script artifact check passed.");
    } else writeFileSync(target, output, "utf8");
  }
}
