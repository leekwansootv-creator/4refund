import { writeFileSync } from "node:fs";
import { basename, dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");

/** 운영 Code.gs와 분리된, 접수·메일·트리거가 없는 빈 시트 준비 bundle을 생성합니다. */
export async function buildEmptyStoragePreparationBundle() {
  const result = await build({
    absWorkingDir: root,
    entryPoints: [
      "integrations/google-apps-script/quick-estimate/src/empty-storage-preparation.ts",
    ],
    bundle: true,
    charset: "utf8",
    format: "iife",
    globalName: "QuickEstimatePreparation",
    legalComments: "none",
    platform: "browser",
    target: ["es2019"],
    treeShaking: true,
    write: false,
    plugins: [
      {
        name: "preparation-browser-boundary",
        setup(builder) {
          builder.onResolve({ filter: /\/components\// }, (args) => ({
            path: args.path,
            external: true,
            sideEffects: false,
          }));
        },
      },
    ],
    banner: { js: "// Generated by scripts/build-empty-storage-preparation.mjs. Do not edit." },
    footer: {
      js: [
        "function prepareEmptyQuickEstimateStorage() { return QuickEstimatePreparation.prepareEmptyQuickEstimateStorage(); }",
        "function verifyEmptyQuickEstimateStorage() { return QuickEstimatePreparation.verifyEmptyQuickEstimateStorage(); }",
      ].join("\n"),
    },
  });
  const source = result.outputFiles[0]?.text;
  if (
    !source ||
    /__require\(|require\(|\b(?:MailApp|GmailApp|ScriptApp|UrlFetchApp|doPost|setupQuickEstimateStorage)\b/u.test(
      source,
    )
  )
    throw new Error("준비 bundle에 금지된 runtime 또는 접수·메일·트리거 의존성이 있습니다.");
  return source;
}

const current = fileURLToPath(import.meta.url);
if (process.argv[1] && resolve(process.argv[1]) === current) {
  const output = process.argv[2] ? resolve(process.argv[2]) : "";
  if (basename(output) !== "Preparation.gs")
    throw new Error("출력 파일명은 Preparation.gs여야 합니다. Code.gs를 덮어쓰지 않습니다.");
  writeFileSync(output, await buildEmptyStoragePreparationBundle(), {
    encoding: "utf8",
    flag: "wx",
  });
  console.log("Preparation.gs generated without overwriting an existing file.");
}
