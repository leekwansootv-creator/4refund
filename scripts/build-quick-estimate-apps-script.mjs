import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import { build } from "esbuild";

const projectRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const integrationRoot = resolve(projectRoot, "integrations/google-apps-script/quick-estimate");
const entrypoint = resolve(integrationRoot, "src/entrypoint.ts");
const outputPath = resolve(integrationRoot, "Code.gs");

/** TypeScript 원본을 Apps Script 전역 진입점이 포함된 단일 V8 bundle로 생성합니다. */
export async function buildQuickEstimateAppsScriptBundle() {
  const result = await build({
    entryPoints: [entrypoint],
    bundle: true,
    charset: "utf8",
    format: "iife",
    globalName: "QuickEstimateWebApp",
    legalComments: "none",
    minify: false,
    platform: "browser",
    target: ["es2019"],
    treeShaking: true,
    plugins: [
      {
        name: "apps-script-browser-boundary",
        setup(builder) {
          // 공개 barrel의 UI re-export는 실행하지 않습니다. 실제 UI 사용은 아래 bundle 검사로 실패합니다.
          builder.onResolve({ filter: /\/components\// }, (args) => ({
            path: args.path,
            external: true,
            sideEffects: false,
          }));
        },
      },
    ],
    write: false,
    banner: {
      js: "// Generated by scripts/build-quick-estimate-apps-script.mjs. Do not edit.",
    },
    footer: {
      js: [
        "function migrateQuickEstimateAttribution() {",
        "  return QuickEstimateWebApp.migrateQuickEstimateAttribution();",
        "}",
        "function doPost(e) {",
        "  return QuickEstimateWebApp.doPost(e);",
        "}",
        "function setupQuickEstimateStorage() {",
        "  return QuickEstimateWebApp.setupQuickEstimateStorage();",
        "}",
        "function syncQuickEstimateConsultationRows() {",
        "  return QuickEstimateWebApp.syncQuickEstimateConsultationRows();",
        "}",
        "function onEditQuickEstimateConsultation(e) {",
        "  return QuickEstimateWebApp.onEditQuickEstimateConsultation(e);",
        "}",
        "function runQuickEstimateOperationsCheck() {",
        "  return QuickEstimateWebApp.runQuickEstimateOperationsCheck();",
        "}",
      ].join("\n"),
    },
  });
  const outputFile = result.outputFiles[0];

  if (outputFile === undefined) {
    throw new Error("Apps Script bundle을 생성하지 못했습니다.");
  }
  if (/__require\(|require\(/u.test(outputFile.text))
    throw new Error("Apps Script bundle에 브라우저 또는 외부 runtime 의존성이 남아 있습니다.");

  return outputFile.text;
}

async function run() {
  const generated = await buildQuickEstimateAppsScriptBundle();
  const shouldCheck = process.argv.includes("--check");

  if (shouldCheck) {
    const current = existsSync(outputPath) ? readFileSync(outputPath, "utf8") : "";

    if (current !== generated) {
      console.error(
        "Code.gs가 TypeScript 원본과 다릅니다. npm run build:apps-script를 실행하세요.",
      );
      process.exitCode = 1;
      return;
    }

    console.log("Apps Script artifact check passed.");
    return;
  }

  writeFileSync(outputPath, generated, "utf8");
  console.log("Apps Script artifact generated.");
}

const currentFile = fileURLToPath(import.meta.url);
const invokedFile = process.argv[1] ? resolve(process.argv[1]) : "";

if (currentFile === invokedFile) {
  await run();
}
